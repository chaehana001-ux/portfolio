import fs from 'node:fs';
const file='dist/index.html';
let html=fs.readFileSync(file,'utf8');
const start=html.indexOf('<section class="section-messages"');
const next=html.indexOf('<section class="section-mejiro-data"',start);
const end=html.lastIndexOf('</section>',next)+10;
if(start<0||next<0||end<start) throw new Error('Messages not found');
const section=html.slice(start,end);
html=html.slice(0,start)+html.slice(end);
const skills=html.indexOf('<section class="section-skills');
const marker='</section>\n            </div>\n          </div>';
const normalized=html.replace(/\r\n/g,'\n');
const target=normalized.indexOf(marker,skills);
if(target<0) throw new Error('Skill wrapper not found');
html=normalized.slice(0,target+marker.length)+'\n'+section+'\n'+normalized.slice(target+marker.length);
fs.writeFileSync(file,html);
const bundleFile='dist/assets/js/bundle.js';
let bundle=fs.readFileSync(bundleFile,'utf8');
const old='[{section:e.lookbook,point:e.point1,label:"ABOUT ME"},{section:e.messages,point:e.point2,label:"MESSAGES"},{section:e.mejiroData,point:e.point3,label:"MEJIRO DATA"},{section:e.admissions,point:e.point4,label:"ADMISSIONS"},{section:e.movie,point:e.point5,label:"MOVIE"},{section:e.information,point:e.pointGoal,label:""}]';
const updated='[{section:e.lookbook,point:e.point1,label:"ABOUT ME"},{section:e.mejiroData,point:e.point2,label:"MEJIRO DATA"},{section:e.admissions,point:e.point3,label:"ADMISSIONS"},{section:e.movie,point:e.point4,label:"MOVIE"},{section:e.information,point:e.point5,label:"SKILL"},{section:e.messages,point:e.pointGoal,label:"MESSAGES"}]';
if(!bundle.includes(old)) throw new Error('Progress order not found');
fs.writeFileSync(bundleFile,bundle.replace(old,updated));
