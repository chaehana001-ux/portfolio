import fs from 'node:fs';
const file = new URL('../dist/index.html', import.meta.url);
let html = fs.readFileSync(file, 'utf8');
const start = html.indexOf('<footer');
const end = html.indexOf('</footer>', start);
if (start < 0 || end < 0) throw new Error('Footer not found');
let footer = html.slice(start, end);
const logoStart = footer.indexOf('<div class="logo"');
const svgStart = footer.indexOf('<svg', logoStart);
const svgEnd = footer.indexOf('</svg>', svgStart) + 6;
if (logoStart < 0 || svgStart < 0) throw new Error('Footer logo not found');
const svg = `<svg class="footer-contact-title" role="img" aria-label="CONTACT" viewBox="0 0 753 238" overflow="visible"><title>CONTACT</title><defs><path id="footer-contact-arc" d="M 34,180 Q 376.5,70 719,180"/></defs><g data-item="logoText" data-anime-item="char-md"><text text-anchor="middle" font-size="148" textLength="655" lengthAdjust="spacingAndGlyphs"><textPath href="#footer-contact-arc" startOffset="50%">CONTACT</textPath></text></g></svg>`;
footer = footer.slice(0, svgStart) + svg + footer.slice(svgEnd);
html = html.slice(0, start) + footer + html.slice(end);
fs.writeFileSync(file, html);
